def number(value):
    return f"{int(float(value)):,}"


def currency(value):
    return f"${float(value):,.2f}"


def compact_currency(value):
    value = float(value)

    if abs(value) >= 1_000_000:
        return f"${value / 1_000_000:,.2f}M"

    if abs(value) >= 1_000:
        return f"${value / 1_000:,.1f}K"

    return currency(value)


def metric_row(items):
    """Display executive metrics in responsive columns."""
    columns = st.columns(len(items))

    for column, (label, value, help_text) in zip(
        columns, items
    ):
        with column:
            st.metric(
                label=label,
                value=value,
                help=help_text,
            )


def section(title, description=None):
    st.subheader(title)

    if description:
        st.markdown(
            f'<div class="section-note">{description}</div>',
            unsafe_allow_html=True,
        )


def bar_chart(df, category, value, horizontal=False):
    chart = df[[category, value]].copy()

    chart[value] = pd.to_numeric(
        chart[value], errors="coerce"
    ).fillna(0)

    if horizontal:
        chart = chart.sort_values(
            value, ascending=True
        )

        st.bar_chart(
            chart,
            x=value,
            y=category,
            horizontal=True,
            use_container_width=True,
        )
    else:
        st.bar_chart(
            chart.set_index(category)[value],
            use_container_width=True,
        )


